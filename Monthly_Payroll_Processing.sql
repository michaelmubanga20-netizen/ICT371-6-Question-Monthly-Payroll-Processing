

CREATE TABLE employees(
 employee_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,full_name text NOT NULL,
 basic_salary numeric(12,2) NOT NULL CHECK(basic_salary>=0),
 allowance numeric(12,2) NOT NULL CHECK(allowance>=0),
 deduction numeric(12,2) NOT NULL CHECK(deduction>=0),active boolean NOT NULL DEFAULT true
);
CREATE TABLE payroll(
 payroll_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 employee_id integer NOT NULL REFERENCES employees(employee_id),
 pay_month date NOT NULL CHECK(EXTRACT(DAY FROM pay_month)=1),
 gross_pay numeric(12,2) NOT NULL,net_pay numeric(12,2) NOT NULL,
 UNIQUE(employee_id,pay_month)
);
CREATE TABLE salary_audit(
 audit_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,employee_id integer NOT NULL REFERENCES employees(employee_id),
 old_salary numeric(12,2) NOT NULL,new_salary numeric(12,2) NOT NULL,changed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
