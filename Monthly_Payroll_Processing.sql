CREATE OR REPLACE FUNCTION fn_net_pay(p_employee_id integer)
RETURNS numeric(12,2) LANGUAGE plpgsql AS $$
DECLARE v_basic numeric(12,2);v_allow numeric(12,2);v_deduct numeric(12,2);v_net numeric(12,2);
BEGIN
 SELECT basic_salary,allowance,deduction INTO v_basic,v_allow,v_deduct FROM employees WHERE employee_id=p_employee_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown employee ID %',p_employee_id; END IF;
 v_net:=v_basic+v_allow-v_deduct;
 IF v_net<0 THEN RAISE EXCEPTION 'Computed net pay cannot be negative'; END IF;
 RETURN v_net;
END $$;

CREATE OR REPLACE PROCEDURE pr_process_payroll(p_month date)
LANGUAGE plpgsql AS $$
DECLARE e record; v_net numeric(12,2);
BEGIN
 IF p_month IS NULL OR EXTRACT(DAY FROM p_month)<>1 THEN RAISE EXCEPTION 'Pay month must be the first day of a month'; END IF;
 FOR e IN SELECT * FROM employees WHERE active=true LOOP
  v_net:=fn_net_pay(e.employee_id);
  INSERT INTO payroll(employee_id,pay_month,gross_pay,net_pay)
  VALUES(e.employee_id,p_month,e.basic_salary+e.allowance,v_net)
  ON CONFLICT(employee_id,pay_month) DO NOTHING;
 END LOOP;
END $$;

CREATE OR REPLACE FUNCTION trg_salary_audit_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.basic_salary IS DISTINCT FROM NEW.basic_salary THEN
  INSERT INTO salary_audit(employee_id,old_salary,new_salary) VALUES(NEW.employee_id,OLD.basic_salary,NEW.basic_salary);
 END IF;
 RETURN NEW;
END $$;
